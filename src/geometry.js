  G.buildMushroom = function (seed) {
    var rng = new M.RNG((seed || 0) + 5);
    var b = new Builder();
    var stemH = rng.range(0.42, 0.70);
    var capR = rng.range(0.22, 0.32);
    // stem
    b.reset().setPart(0, 0, 0, 2).rotEuler(-Math.PI / 2, 0, 0);
    b.limb(stemH, 0.048, 0.070, 10, 3, 0, 0.55);
    //  CLEAR THE STEM'S ROTATION BEFORE THE CAP.
    //
    //  limb() runs along +z, so the stem needs rotEuler(-PI/2) to stand up.
    //  The cap below is authored directly in world axes - its y already has
    //  stemH added in - so it must be built with no rotation at all. Leaving
    //  the stem's rotation set fed the cap through (x,y,z) -> (x, z, -y) and
    //  laid it flat on the sand behind the stem, a vertical disc reading as a
    //  dartboard in the dirt: bbox y -0.226..0.462, z -0.584..0.067, with the
    //  cap's whole extent in z where it belonged in y.
    b.reset();
    // cap: a domed skirt with a rolled rim, built as a lathe so the
    // underside is a real surface the light can catch
    var segU = 18, segV = 8;
    var base = b.vertCount();
    for (var j = 0; j <= segV; j++) {
      var v = j / segV;
      // profile from apex (v=0) out to the rim and slightly under
      var prof = Math.sin(v * Math.PI * 0.62);
      var r = capR * prof * (1 + 0.10 * Math.sin(v * 7.0));
      var y = stemH + capR * 0.72 * Math.cos(v * Math.PI * 0.62) - capR * 0.12 * v * v;
      for (var i = 0; i <= segU; i++) {
        var u = i / segU, th = u * M.TAU;
        var ripple = 1 + 0.055 * Math.sin(th * 7.0 + rng.s * 0.0);
        b.setPart(0, v, 0, 2);
        b.vert(Math.cos(th) * r * ripple, y, Math.sin(th) * r * ripple,
          Math.cos(th) * prof, Math.max(0.25, Math.cos(v * 1.9)), Math.sin(th) * prof, u, v);
      }
    }
    for (j = 0; j < segV; j++) for (i = 0; i < segU; i++) {
      var a = base + j * (segU + 1) + i, bb = a + segU + 1;
      b.quad(a, a + 1, bb + 1, bb);
    }
    //  Skirt: close the cap by folding the rim back down and inward. This
    //  gives a real shaded underside instead of a flat disc floating at the
    //  cap's waist (which read as a dartboard lying on the ground).
    var rimY = stemH + capR * 0.72 * Math.cos(Math.PI * 0.62) - capR * 0.12;
    var rimR = capR * Math.sin(Math.PI * 0.62);
    var under = 5;
    var ub = b.vertCount();
    for (var w = 0; w <= under; w++) {
      var tv = w / under;
      var rr = rimR * (1 - tv) + capR * 0.10 * tv;
      var yy = rimY + tv * capR * 0.30;
      for (i = 0; i <= segU; i++) {
        var th2 = i / segU * M.TAU;
        b.setPart(0, 1, 0, 3);
        b.vert(Math.cos(th2) * rr, yy, Math.sin(th2) * rr,
          Math.cos(th2) * 0.25, -1, Math.sin(th2) * 0.25, i / segU, tv);
      }
    }
    for (w = 0; w < under; w++) for (i = 0; i < segU; i++) {
      var ua = ub + w * (segU + 1) + i, ubb = ua + segU + 1;
      b.quad(ua, ubb, ubb + 1, ua + 1);
    }
    return b;
  };

  G.buildCrystal = function (seed) {
    // sugar crystal: irregular prism
    var rng = new M.RNG(seed || 11);
    var b = new Builder();
    var sides = 6;
    var base = b.vertCount();
    var rr = [];
    for (var i = 0; i < sides; i++) rr.push(rng.range(0.6, 1.15));
    for (var k = 0; k < 2; k++) {
      var y = k ? 0.62 : 0.0;
      var sc = k ? 0.72 : 1.0;
      for (i = 0; i <= sides; i++) {
        var th = (i % sides) / sides * M.TAU + 0.3;
        var r = rr[i % sides] * sc * 0.34;
        b.vert(Math.cos(th) * r, y, Math.sin(th) * r, Math.cos(th), 0.1, Math.sin(th), i / sides, k);
      }
    }
    for (i = 0; i < sides; i++) {
      var a = base + i, bb = a + sides + 1;
      b.quad(a, bb, bb + 1, a + 1);
    }
    var tip = b.vert(0, 0.95, 0, 0, 1, 0, 0.5, 1);
    var bot = b.vert(0, -0.16, 0, 0, -1, 0, 0.5, 0);
    for (i = 0; i < sides; i++) {
      b.tri(tip, base + sides + 1 + i, base + sides + 2 + i);
      b.tri(bot, base + i + 1, base + i);
    }
    return b;
  };

  G.buildSeed = function () {
    var b = new Builder();
    b.reset().setPart(0, 0, 0, 0).scl(0.22, 0.17, 0.30).at(0, 0.17, 0);
    b.ellipsoid(11, 8);
    return b;
  };

  //  A puddle, not a bead. Water that has settled on soil spreads into a
  //  shallow lens with a slightly domed middle and a thin feathered edge -
  //  drawing it as the falling-droplet mesh made pools look like glass marbles
  //  sitting on the dirt.
  G.buildPuddle = function () {
    var b = new Builder();
    var rings = 7, segs = 24;
    var base = b.vertCount();
    for (var j = 0; j <= rings; j++) {
      var v = j / rings;
      var r = v;
      // domed centre falling to a very thin rim
      var h = Math.cos(v * Math.PI * 0.5);
      h = h * h * 0.17;
      for (var i = 0; i <= segs; i++) {
        var th = i / segs * M.TAU;
        // a slightly irregular outline so it never reads as a perfect circle
        var wob = 1 + 0.06 * Math.sin(th * 3.0) + 0.035 * Math.sin(th * 7.0 + 1.3);
        var nx = Math.cos(th) * v * 0.55, nz = Math.sin(th) * v * 0.55;
        b.setPart(0, v, 0, 0);
        b.vert(Math.cos(th) * r * wob, h, Math.sin(th) * r * wob,
          nx, 1.0, nz, i / segs, v);
      }
    }
    for (j = 0; j < rings; j++) for (i = 0; i < segs; i++) {
      var a = base + j * (segs + 1) + i, bb = a + segs + 1;
      b.quad(a, a + 1, bb + 1, bb);
    }
    return b;
  };

  G.buildDroplet = function () {
    var b = new Builder();
    var su = 16, sv = 12, base = b.vertCount();
    for (var j = 0; j <= sv; j++) {
      var v = j / sv, phi = v * Math.PI;
      var sp = Math.sin(phi), cp = Math.cos(phi);
      var squash = 1.0 - 0.42 * M.smoothstep(0.4, 1.0, v);
      for (var i = 0; i <= su; i++) {
        var u = i / su, th = u * M.TAU;
        b.vert(sp * Math.cos(th) * (1 + (1 - squash) * 0.5), cp * squash * 0.86 + 0.14, sp * Math.sin(th) * (1 + (1 - squash) * 0.5),
          sp * Math.cos(th), cp, sp * Math.sin(th), u, v);
      }
    }
    for (j = 0; j < sv; j++) for (i = 0; i < su; i++) {
      var a = base + j * (su + 1) + i, bb = a + su + 1;
      b.quad(a, a + 1, bb + 1, bb);
    }
    return b;
  };

  // dead insect / aphid : protein food
