  // ------------------------------------------------------------------
  //  PREDATOR : wolf spider
  // ------------------------------------------------------------------
  G.buildSpider = function () {
    var b = new Builder();
    var P = G.PART;
    var s, L, i;

  //  RIGID LIMB PART ID.
  //
  //  A limb needs two things that used to be in conflict. The fragment
  //  shader gives limbs their dark matte material - and sets limb=1.0 to
  //  kill the fresnel rim - on the test pid > 2.5 && pid < 10.5. The vertex
  //  shader's animPart rotates 3..8 (legs), 9 (antenna) and 10 (mandible)
  //  about attach points hard-coded for an ANT, which mangles anything
  //  bigger. Parking limbs on part 0 avoided the mangling but lost the
  //  material, and the legs came out pale against a dark body - exactly the
  //  "read as white paper" failure the shader's own comment warns about.
  //
  //  2.75 sits in the gap between the two: it passes the material test and
  //  matches NO animation branch. Dark matte limbs, no fresnel rim, no
  //  rotation about somebody else's hip.
  var LIMB = 2.75;


    //  a limb between two points, so the tables below read as anatomy
    var bone = function (side, p0, p1, r0, r1, nseg, rings, t0, t1) {
      var ax = side * p0[0], ay = p0[1], az = p0[2];
      var bx = side * p1[0], by = p1[1], bz = p1[2];
      var dx = bx - ax, dy = by - ay, dz = bz - az;
      b.reset().setPart(LIMB, 0, side, 0).at(ax, ay, az).rotFromAxis([dx, dy, dz]);
      b.limb(Math.sqrt(dx * dx + dy * dy + dz * dz), r0, r1, nseg, rings, t0, t1);
    };

    // --- CEPHALOTHORAX ------------------------------------------------
    //  Wide and LOW, and deliberately wider than the abdomen (0.375 against
    //  0.305). The old build was 0.34 against a 0.42 abdomen, which put the
    //  animal's widest point at its tail and made it read as an egg with a
    //  bump in front. A hunting spider's mass is at the shoulders, where the
    //  legs come out.
    b.reset().setPart(P.THORAX, 0, 0, 0).at(0, 0.400, 0.130).scl(0.375, 0.205, 0.365);
    b.ellipsoid(16, 11);

    //  Ocular tubercle: the raised head region, standing 0.056 proud of the
    //  carapace hull, so their intersection is a crease AND the eyes get a
    //  face to sit on instead of a flat forehead. It is on P.HEAD, not
    //  P.THORAX, on purpose: animPart has no branch for pid 1, so the
    //  tubercle and the eyes pinned to it are both perfectly still. On the
    //  carapace it would bob 0.004 under stationary eyes and the small ones
    //  would submerge and re-emerge once per step.
    b.reset().setPart(P.HEAD, 0, 0, 0).at(0, 0.478, 0.350).scl(0.210, 0.150, 0.235);
    b.ellipsoid(13, 9);

    // --- THE PEDICEL --------------------------------------------------
    //  The waist is the whole difference between a spider and a beetle, and
    //  the old mesh had none: the two ellipsoids interpenetrated over 0.21
    //  of z and the outline swelled monotonically from face to tail. Here
    //  the narrowest cross-section is 0.082 half-width at z = -0.315,
    //  against a 0.375 shoulder - a 22% pinch, tighter than the ant's own
    //  petiole. It is pinched in Y too (0.088 against 0.245), so the waist
    //  shows from any yaw and not just from above. DO NOT WIDEN IT.
    b.reset().setPart(P.THORAX, 0, 0, 0).at(0, 0.400, -0.262).scl(0.095, 0.088, 0.105);
    b.ellipsoid(9, 7);

    // --- ABDOMEN ------------------------------------------------------
    //  Three overlapping masses, not one egg. Centres are spaced ~1.04x
    //  their z-radius, the same band the woodlouse tergites and the cricket
    //  abdomen use: deep enough not to gap, shallow enough that the crossing
    //  stays angular and inks. The steps are TRANSVERSE on purpose - at a
    //  five-degree camera a transverse step breaks the top outline, where a
    //  longitudinal stripe would run edge-on and contribute nothing.
    //
    //  Stays on P.GASTER for the +/-0.008 bob. With every limb now rigid it
    //  is the only motion left on the animal, and the pedicel is buried
    //  0.057 into the front segment, far more than the 0.012 of shear.
    b.reset().setPart(P.GASTER, 0, 0, 0).at(0, 0.408, -0.505).scl(0.285, 0.245, 0.195);
    b.ellipsoid(14, 10);
    b.reset().setPart(P.GASTER, 0, 0, 0).at(0, 0.398, -0.710).scl(0.305, 0.258, 0.200);
    b.ellipsoid(14, 10);
    b.reset().setPart(P.GASTER, 0, 0, 0).at(0, 0.352, -0.905).scl(0.208, 0.175, 0.180);
    b.ellipsoid(10, 7);

    // --- EYES ---------------------------------------------------------
    //  The rule that fixes this: each bead's CENTRE sits exactly ON the
    //  tubercle surface, so a full hemisphere protrudes and the tangency
    //  circle is a hard normal break the ink pass draws as a ring - no
    //  collar geometry needed. The old cluster pinned all eight to a flat
    //  z = 0.36 plane, which left FOUR of them entirely inside the carapace
    //  (q = 0.596 and 0.694) and the rest protruding 0.003 to 0.020.
    //
    //  The other half is size hierarchy: the two posterior median eyes are
    //  r = 0.076, roughly 5.6x the projected area of the old beads and 36%
    //  of the head half-width. They are the recognition cue, not the count.
    //  Keep flag = 1 on every eye - shaders.js:599 keys the glossy black
    //  material (rough 0.09, spec 2.2) on it, and that specular highlight is
    //  the one genuinely BRIGHT thing on this animal.
    for (s = -1; s <= 1; s += 2) {
      // posterior median: the two big forward-facing eyes
      b.reset().setPart(P.HEAD, 0, s, 1).at(s * 0.0968, 0.5121, 0.5479).scl(0.076, 0.076, 0.068);
      b.ellipsoid(9, 7);
      // posterior lateral: up on the top corners, so the face survives a
      // near-overhead look and shows as bumps on the head outline from side on
      b.reset().setPart(P.HEAD, 0, s, 1).at(s * 0.1672, 0.5596, 0.3734).scl(0.042, 0.042, 0.038);
      b.ellipsoid(7, 5);
      // anterior row: four small ones low on the face, clear of the fangs
      b.reset().setPart(P.HEAD, 0, s, 1).at(s * 0.0420, 0.3874, 0.5405).scl(0.030, 0.030, 0.026);
      b.ellipsoid(6, 4);
      b.reset().setPart(P.HEAD, 0, s, 1).at(s * 0.1221, 0.3948, 0.5007).scl(0.028, 0.028, 0.025);
      b.ellipsoid(6, 4);
    }

    // --- CHELICERAE AND PEDIPALPS -------------------------------------
    for (s = -1; s <= 1; s += 2) {
      //  Paturon: a stout block hanging 0.149 below the face, anchored in
      //  the carapace so the join is a crease. The pair nearly meets at the
      //  midline, which gives one more line down the jaw. The old build had
      //  no paturon at all - just a bare 23:1 cone that read as a whisker.
      b.reset().setPart(LIMB, 0, s, 0).at(s * 0.098, 0.290, 0.455).scl(0.088, 0.115, 0.090);
      b.ellipsoid(8, 6);
      //  Fang: DOWN at 63 degrees (the old one was 30) and INWARD - note the
      //  -s x-term, the same convergence the beetle's jaws and the
      //  centipede's venom claws use. Splayed apart, a pair of appendages
      //  reads as two more legs; converged, it reads as a pincer. Tips land
      //  at x = +/-0.056, so they close without crossing.
      b.reset().setPart(LIMB, 0, s, 0).at(s * 0.095, 0.215, 0.470).rotFromAxis([-s * 0.28, -1.0, 0.42]);
      b.limb(0.155, 0.032, 0.006, 6, 2, 0, 1);

      //  PEDIPALPS. The mesh had none, and on a wolf spider they are the
      //  instant tell. They read for a reason that survives darkness: they
      //  are the only appendage that goes forward and DOWN while all eight
      //  legs arch UP, and they are thicker (0.046) than a leg's tibia
      //  (0.050 -> 0.030) at half the length, so they never read as a ninth
      //  leg. The clubbed tip reaches z = 0.93, filling the gap between the
      //  fangs at 0.53 and the front feet at 1.01.
      bone(s, [0.175, 0.330, 0.400], [0.290, 0.255, 0.640], 0.046, 0.034, 6, 2, 0, 0.5);
      bone(s, [0.290, 0.255, 0.640], [0.245, 0.130, 0.860], 0.034, 0.026, 6, 2, 0.5, 0.3);
      b.reset().setPart(LIMB, 0, s, 0).at(s * 0.240, 0.125, 0.880).scl(0.042, 0.038, 0.052);
      b.ellipsoid(7, 5);
    }

    // --- EIGHT LEGS ---------------------------------------------------
    //  Three segments: femur out and UP to a knee standing well clear of the
    //  back, tibia the long span back DOWN to an ankle, then a short tarsus
    //  lying along the sand at about 23 degrees. A spider stands on the
    //  LENGTH of its foot; the old two-segment leg speared the ground at 50
    //  degrees and terminated on a 0.010 needle, which at scale 0.62 is
    //  0.006 world units and simply aliased away.
    //
    //  Three separate fixes to the table itself:
    //  - knee heights all DIFFER (0.845 to 0.965). The old build used the
    //    literal 0.95 for every leg, so at the tank's near-side-on default
    //    camera the knees sat on one flat horizontal like a picket fence -
    //    and the old `spread` repeated 0.95 at index 1 and 3, so two legs
    //    per side projected onto exactly the same screen line at yaw 0.
    //  - feet are NOT evenly spaced. The old z were 0.983 / 0.333 / -0.318 /
    //    -0.968, gaps of 0.650 / 0.651 / 0.650: a comb, not a spider. These
    //    group 2 + 2, with the middle gap about twice the outer ones.
    //  - length order is IV > I > II > III (1.995 / 1.917 / 1.790 / 1.716),
    //    the Lycosid order; leg IV is the long propulsive one. The old build
    //    ran I > IV > II > III.
    //         hip                        knee                       ankle                       foot
    var LEGS = [
      { h: [0.225, 0.375,  0.255], k: [0.520, 0.965,  0.560], a: [0.865, 0.095,  0.850], f: [0.975, 0.014,  1.010] },
      { h: [0.235, 0.380,  0.130], k: [0.620, 0.895,  0.240], a: [1.070, 0.095,  0.440], f: [1.205, 0.014,  0.560] },
      { h: [0.225, 0.375, -0.020], k: [0.600, 0.845, -0.230], a: [1.045, 0.095, -0.380], f: [1.175, 0.014, -0.500] },
      { h: [0.155, 0.370, -0.165], k: [0.520, 0.940, -0.600], a: [0.895, 0.095, -0.900], f: [1.020, 0.014, -1.060] }
    ];
    for (L = 0; L < 8; L++) {
      var side = L < 4 ? 1 : -1;
      var g = LEGS[L % 4];
      // femur: out and UP. 0.078 -> 0.052 over 0.64-0.80, about 11:1.
      bone(side, g.h, g.k, 0.078, 0.052, 7, 2, 0, 0.35);
      //  PATELLA. The single most valuable bead on the animal. The old leg
      //  had NO radius step at the knee - femur ended at 0.038 and tibia
      //  began at 0.038 - so a 100-degree bend was a kink in a constant tube
      //  with a faceted mitre in it, which is the definition of wire. At
      //  0.066 it is 27% fatter than either tube, and because these stand
      //  0.19-0.31 above the highest point of the body, eight of them are a
      //  row of knuckles ON THE OUTLINE, which is the one place contrast
      //  does not have to fight a multiply on a near-black surface.
      b.reset().setPart(LIMB, 0, side, 0).at(side * g.k[0], g.k[1], g.k[2]).scl(0.066, 0.066, 0.066);
      b.ellipsoid(6, 5);
      // tibia: back DOWN. 0.050 -> 0.030 over ~0.94, about 24:1 - was 50:1.
      bone(side, g.k, g.a, 0.050, 0.030, 6, 2, 0.35, 0.40);
      //  tarsus: the only part allowed to go thin, and it is short. Near
      //  horizontal along the sand, which is what gives the leg a stance
      //  instead of a point, and eight ground-contact lines for the ink.
      bone(side, g.a, g.f, 0.028, 0.013, 5, 1, 0.75, 0.25);
    }

    return b;
  };

  // ------------------------------------------------------------------
  //  ENVIRONMENT
  // ------------------------------------------------------------------
  //  Surface heightfield patch (the soil top / terrarium landscape)
  G.buildSurface = function (w, d, nx, nz, heightFn) {
    var b = new Builder();
    var base = b.vertCount();
    for (var j = 0; j <= nz; j++) {
      for (var i = 0; i <= nx; i++) {
        var u = i / nx, v = j / nz;
        var x = (u - 0.5) * w, z = (v - 0.5) * d;
        var y = heightFn(x, z);
        var e = 0.12;
        var hx = heightFn(x + e, z), hz = heightFn(x, z + e);
        var nX = -(hx - y) / e, nZ = -(hz - y) / e;
        var l = Math.sqrt(nX * nX + 1 + nZ * nZ);
        b.vert(x, y, z, nX / l, 1 / l, nZ / l, u * 8, v * 8);
      }
    }
    for (j = 0; j < nz; j++) for (i = 0; i < nx; i++) {
      var a = base + j * (nx + 1) + i, bb = a + nx + 1;
      b.quad(a, bb, bb + 1, a + 1);
    }
    return b;
  };

  //  Glass panels of a vitrine (open top), inward + outward faces
  G.buildGlassBox = function (hx, hy, hz) {
    var b = new Builder();
    b.reset().setPart(0, 0, 0, 0);
    var sides = [
      { n: [0, 0, 1], c: [0, 0, hz], u: [1, 0, 0], v: [0, 1, 0], su: hx, sv: hy },
      { n: [0, 0, -1], c: [0, 0, -hz], u: [1, 0, 0], v: [0, 1, 0], su: hx, sv: hy },
      { n: [1, 0, 0], c: [hx, 0, 0], u: [0, 0, 1], v: [0, 1, 0], su: hz, sv: hy },
      { n: [-1, 0, 0], c: [-hx, 0, 0], u: [0, 0, 1], v: [0, 1, 0], su: hz, sv: hy }
    ];
    for (var k = 0; k < sides.length; k++) {
      var S = sides[k];
      var base = b.vertCount();
      for (var q = 0; q < 4; q++) {
        var uu = (q === 1 || q === 2) ? 1 : -1;
        var vv = (q >= 2) ? 1 : -1;
        b.vert(S.c[0] + S.u[0] * uu * S.su + S.v[0] * vv * S.sv,
          S.c[1] + S.u[1] * uu * S.su + S.v[1] * vv * S.sv,
          S.c[2] + S.u[2] * uu * S.su + S.v[2] * vv * S.sv,
          S.n[0], S.n[1], S.n[2], (uu + 1) * 0.5, (vv + 1) * 0.5);
      }
      b.quad(base, base + 1, base + 2, base + 3);
    }
    return b;
  };

  //  Wooden / metal frame rails around a vitrine
  G.buildFrame = function (hx, hy, hz, t) {
    var b = new Builder();
    var bars = [];
    var ys = [-hy, hy];
    for (var yi = 0; yi < 2; yi++) {
      var y = ys[yi];
      bars.push([0, y, hz, hx + t, t, t], [0, y, -hz, hx + t, t, t]);
      bars.push([hx, y, 0, t, t, hz + t], [-hx, y, 0, t, t, hz + t]);
    }
    for (var sx = -1; sx <= 1; sx += 2) for (var sz = -1; sz <= 1; sz += 2) {
      bars.push([sx * hx, 0, sz * hz, t, hy, t]);
    }
    for (var i = 0; i < bars.length; i++) {
      var B = bars[i];
      b.reset().setPart(0, 0, 0, 0).at(B[0], B[1], B[2]);
      b.boxFaces(B[3], B[4], B[5], false);
    }
    return b;
  };

  //  Connection tube between two farms (glass pipe along a bezier)
  G.buildTube = function (segments, radialSegs) {
    // unit tube along +Z from 0..1 ; the shader bends it via uTubeCtrl
    var b = new Builder();
    var base = b.vertCount();
    for (var j = 0; j <= segments; j++) {
      var t = j / segments;
      for (var i = 0; i <= radialSegs; i++) {
        var th = i / radialSegs * M.TAU;
        b.setPart(0, t, 0, 0);
        b.vert(Math.cos(th), Math.sin(th), t, Math.cos(th), Math.sin(th), 0, i / radialSegs, t);
      }
    }
    for (j = 0; j < segments; j++) for (i = 0; i < radialSegs; i++) {
      var a = base + j * (radialSegs + 1) + i, bb = a + radialSegs + 1;
      b.quad(a, bb, bb + 1, a + 1);
    }
    return b;
  };

  //  simple quad for billboards / decals
  //  A rounded blob - the body of one water particle. Subdivided
  //  icosahedron: 42 verts / 80 tris at subdiv 1, which is the cheapest
  //  shape that still reads as a droplet rather than a facet.
  G.buildBlob = function (subdiv) {
    var t = (1 + Math.sqrt(5)) / 2;
    var v = [
      [-1, t, 0], [1, t, 0], [-1, -t, 0], [1, -t, 0],
      [0, -1, t], [0, 1, t], [0, -1, -t], [0, 1, -t],
      [t, 0, -1], [t, 0, 1], [-t, 0, -1], [-t, 0, 1]
    ];
    var f = [
      [0, 11, 5], [0, 5, 1], [0, 1, 7], [0, 7, 10], [0, 10, 11],
      [1, 5, 9], [5, 11, 4], [11, 10, 2], [10, 7, 6], [7, 1, 8],
      [3, 9, 4], [3, 4, 2], [3, 2, 6], [3, 6, 8], [3, 8, 9],
      [4, 9, 5], [2, 4, 11], [6, 2, 10], [8, 6, 7], [9, 8, 1]
    ];
    var i, j;
    for (i = 0; i < v.length; i++) {
      var l = Math.sqrt(v[i][0] * v[i][0] + v[i][1] * v[i][1] + v[i][2] * v[i][2]);
      v[i][0] /= l; v[i][1] /= l; v[i][2] /= l;
    }
    for (var s = 0; s < (subdiv || 0); s++) {
      var mid = {}, nf = [];
      function midpoint(a, b) {
        var k = a < b ? a + '_' + b : b + '_' + a;
        if (mid[k] !== undefined) return mid[k];
        var m = [(v[a][0] + v[b][0]) / 2, (v[a][1] + v[b][1]) / 2, (v[a][2] + v[b][2]) / 2];
        var ml = Math.sqrt(m[0] * m[0] + m[1] * m[1] + m[2] * m[2]);
        m[0] /= ml; m[1] /= ml; m[2] /= ml;
        v.push(m); mid[k] = v.length - 1; return mid[k];
      }
      for (i = 0; i < f.length; i++) {
        var a = f[i][0], b = f[i][1], c = f[i][2];
        var ab = midpoint(a, b), bc = midpoint(b, c), ca = midpoint(c, a);
        nf.push([a, ab, ca], [b, bc, ab], [c, ca, bc], [ab, bc, ca]);
      }
      f = nf;
    }
    var bd = new Builder();
    bd.reset().setPart(0, 0, 0, 0);
    var base = bd.vertCount();
    for (i = 0; i < v.length; i++) {
      var u = 0.5 + Math.atan2(v[i][2], v[i][0]) / (2 * Math.PI);
      var vv = 0.5 - Math.asin(v[i][1]) / Math.PI;
      bd.vert(v[i][0], v[i][1], v[i][2], v[i][0], v[i][1], v[i][2], u, vv);
    }
    for (i = 0; i < f.length; i++) bd.tri(base + f[i][0], base + f[i][1], base + f[i][2]);
    return bd;
  };

  //  Flat annulus in XZ - the aim contour. UV.x runs 0..1 around the ring
  //  and UV.y is 0 at the inner edge, 1 at the outer, so the shader can
  //  dash it and feather it without any extra attributes.
  G.buildRing = function (segs, inner, outer) {
    var b = new Builder();
    b.reset().setPart(0, 0, 0, 0);
    var base = b.vertCount();
    for (var i = 0; i <= segs; i++) {
      var a = i / segs * Math.PI * 2;
      var ca = Math.cos(a), sa = Math.sin(a);
      b.vert(ca * inner, 0, sa * inner, 0, 1, 0, i / segs, 0);
      b.vert(ca * outer, 0, sa * outer, 0, 1, 0, i / segs, 1);
    }
    for (i = 0; i < segs; i++) {
      var o = base + i * 2;
      b.quad(o, o + 2, o + 3, o + 1);
    }
    return b;
  };

  G.buildQuad = function () {
    var b = new Builder();
    var base = b.vertCount();
    b.vert(-1, -1, 0, 0, 0, 1, 0, 0);
    b.vert(1, -1, 0, 0, 0, 1, 1, 0);
    b.vert(1, 1, 0, 0, 0, 1, 1, 1);
    b.vert(-1, 1, 0, 0, 0, 1, 0, 1);
    b.quad(base, base + 1, base + 2, base + 3);
    return b;
  };

  //  unit cube box
  G.buildBox = function (hx, hy, hz, inside) {
    var b = new Builder();
    b.reset().setPart(0, 0, 0, 0);
    b.boxFaces(hx, hy, hz, inside);
    return b;
  };

